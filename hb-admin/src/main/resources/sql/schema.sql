COMMENT ON TABLE  "SYS_USER" IS '用户信息表';

COMMENT ON COLUMN "SYS_USER"."USER_ID" IS '用户ID';

COMMENT ON COLUMN "SYS_USER"."DEPT_ID" IS '部门ID';

COMMENT ON COLUMN "SYS_USER"."USER_NAME" IS '用户账号';

COMMENT ON COLUMN "SYS_USER"."NICK_NAME" IS '用户昵称';

COMMENT ON COLUMN "SYS_USER"."EMAIL" IS '用户邮箱';

COMMENT ON COLUMN "SYS_USER"."PHONE_NUMBER" IS '手机号码';

COMMENT ON COLUMN "SYS_USER"."SEX" IS '用户性别（0男 1女 2未知）';

COMMENT ON COLUMN "SYS_USER"."AVATAR" IS '头像地址';

COMMENT ON COLUMN "SYS_USER"."PASSWORD" IS '密码';

COMMENT ON COLUMN "SYS_USER"."STATUS" IS '帐号状态（0正常 1停用）';

COMMENT ON COLUMN "SYS_USER"."DEL_FLAG" IS '删除标志（0代表存在 2代表删除）';

COMMENT ON COLUMN "SYS_USER"."LOGIN_IP" IS '最后登录IP';

COMMENT ON COLUMN "SYS_USER"."LOGIN_DATE" IS '最后登录时间';

COMMENT ON COLUMN "SYS_USER"."CREATE_BY" IS '创建者';

COMMENT ON COLUMN "SYS_USER"."CREATE_TIME" IS '创建时间';

COMMENT ON COLUMN "SYS_USER"."UPDATE_BY" IS '更新者';

COMMENT ON COLUMN "SYS_USER"."UPDATE_TIME" IS '更新时间';

COMMENT ON COLUMN "SYS_USER"."REMARK" IS '备注';

COMMENT ON COLUMN "SYS_USER"."DOMAIN_ID" IS '导入域id（0表示手动添加）';

COMMENT ON COLUMN "SYS_USER"."OBJECT_GUID" IS 'ad域内用户唯一标识';

COMMENT ON COLUMN "SYS_USER"."LANGUAGE" IS '语言配置(不设置默认为中文)';

